"""The evidence pack index, generated from docs/progress/requirements.json (requirement L.c).

    python3 scripts/evidence_index.py            # print the index (Markdown) to stdout
    python3 scripts/evidence_index.py --write    # write docs/evidence/INDEX.md

One table per area: every requirement, its state, each piece of evidence as a link (a
repository file, or a pull request), and for a blocked item what blocks it. The measures at
the top are the ones `scripts/completion_summary.py` computes, from the same module, so the
index can never disagree with the register.

Why INDEX.md is not committed and compared in a test: `requirements.json` changes in most
pull requests, so a committed copy would be stale after every merge and a test comparing it
would fail pull requests that did nothing wrong. Instead the readiness test checks that the
index generates from the live file, covers every requirement and links only files that exist,
and CI writes the index on every run and keeps it as the build artifact "evidence-index". The
copy that goes into an evidence pack is written with `--write` from the release commit.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import completion_summary as cs  # noqa: E402

ROOT = cs.ROOT
OUT = ROOT / "docs" / "evidence" / "INDEX.md"
REPO_URL = "https://github.com/Praveenkumar101508/ira-care"
AREA_TITLES = {"software": "Software", "ai": "AI", "os": "Operating system",
               "hardware": "Hardware", "external": "External and commercial"}


def _link(ref: str, from_dir: Path) -> str:
    """A Markdown link for one evidence ref: a pull request, or a file relative to the index."""
    m = cs.PR_REF.match(ref)
    if m:
        return f"[#{m.group(1)}]({REPO_URL}/pull/{m.group(1)})"
    path, _, name = ref.partition("::")
    rel = Path(*([".."] * len(from_dir.relative_to(ROOT).parts)), path).as_posix()
    label = f"`{path}`" + (f" `{name}`" if name else "")
    return f"[{label}]({rel})"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(doc: dict, commit: str | None = None) -> str:
    problems = cs.validate(doc)
    if problems:
        raise ValueError("requirements.json does not validate:\n  " + "\n  ".join(problems))
    s = cs.summary(doc)
    from_dir = OUT.parent
    lines = ["# IRA CARE evidence index", "",
             f"Generated by `scripts/evidence_index.py` from `docs/progress/requirements.json` "
             f"(version {doc['version']}{', commit `' + commit + '`' if commit else ''}). "
             "Do not edit by hand.", "",
             "| Measure | Done / total | % |", "|---|---|---|"]
    for key, label, *_ in cs.MEASURES:
        m = s["measures"][key]
        lines.append(f"| {label} | {m['numerator']} / {m['denominator']} | {m['percent']} % |")
    lines += ["", f"States: " + ", ".join(f"{k} {v}" for k, v in s["by_state"].items()) + ".", ""]
    for area in cs.AREAS:
        reqs = [r for r in doc["requirements"] if r["area"] == area]
        if not reqs:
            continue
        lines += [f"## {AREA_TITLES[area]} ({len(reqs)})", "",
                  "| Id | Requirement | State | Evidence or blocker |", "|---|---|---|---|"]
        for r in reqs:
            if r["state"] == "blocked_external":
                what = "blocked: " + _cell(r.get("blocked_by", ""))
            elif r["evidence"]:
                what = "; ".join(f"{e['kind']}: {_link(e['ref'], from_dir)}" for e in r["evidence"])
            else:
                what = "none yet"
            hw = "" if r["hardware_independent"] else " (needs hardware)"
            lines.append(f"| {r['id']} | {_cell(r['title'])}{hw} | {r['state']} | {what} |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true", help=f"write {OUT.relative_to(ROOT)}")
    a = ap.parse_args(argv)
    doc = json.loads(cs.REQUIREMENTS.read_text(encoding="utf-8"))
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                                capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = None
    text = render(doc, commit)
    if a.write:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
