#!/usr/bin/env python3
"""P16-R3 — regenerate `dependency-licences.json` and `sbom.cyclonedx.json`.

── Why this script exists at all ───────────────────────────────────────────

Both artifacts were generated by hand and committed. There was no generator, so
there was no way to reproduce them, no way to see what question had been asked,
and no way to tell a stale answer from a current one except by trusting the file.
`dependency-licences.json` said 187 packages while the lock said 162 — and the
gate that reads it would have kept passing had the missing 25 not been copyleft.

── Why it reads BOTH locks ─────────────────────────────────────────────────

FINDING AM split the dependency set into `requirements.lock` and
`requirements-torch.lock`. Six packages moved from the first to the second —
`jinja2`, `markupsafe`, `mpmath`, `networkx`, `setuptools`, `sympy`. They are
still installed. An inventory built from one lock would have dropped them and
reported a smaller, cleaner position produced by looking away, which is the
exact failure mode P16-04 opened with (`pip-licenses` answering about the wrong
tree).

── What a licence answer is here ───────────────────────────────────────────

PyPI metadata **at the locked version**, in this precedence:

1. `license_expression` — the SPDX field, present on modern metadata.
2. `license` — the legacy free-text field.
3. The `License ::` trove classifiers.
4. The **licence file inside the published artifact**. When the metadata says
   nothing, the wheel usually still ships `dist-info/licenses/LICENSE`, and
   that file is more authoritative than the metadata that omits it. It is
   fetched, its first line recorded verbatim, and the artifact's sha256 stored
   alongside so the answer names the thing it was read from. Nothing is
   inferred: the entry says what the file says.
5. `UNDECLARED` — and absence of a licence field is NOT permission. It is
   recorded as UNDECLARED so it stays visible, and
   `scripts/check_licence_inventory.py` requires each one to be declared and
   explained in a diff.

Packages pinned with a PEP 440 local segment (`2.11.0+cpu`) are queried at their
base release; PyPI has no record of a local build variant.

Run:

    python scripts/build_licence_inventory.py
"""
from __future__ import annotations

import hashlib
import io
import json
import re
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

from _net import fetch

IRA_ROOT = Path(__file__).resolve().parents[1]
LOCKS = (IRA_ROOT / "requirements.lock", IRA_ROOT / "requirements-torch.lock")
INVENTORY = IRA_ROOT / "dependency-licences.json"
SBOM = IRA_ROOT / "sbom.cyclonedx.json"

_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;#\\]+)")


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _base_version(version: str) -> str:
    return version.split("+", 1)[0]


def locked() -> dict[str, tuple[str, str]]:
    """`{normalised name: (version, which lock)}` across both locks."""
    out: dict[str, tuple[str, str]] = {}
    for lock in LOCKS:
        for line in lock.read_text(encoding="utf-8").splitlines():
            if line.startswith("#") or line.startswith(" "):
                continue
            m = _PIN.match(line)
            if m:
                out[_norm(m.group(1))] = (m.group(2), lock.name)
    return out


def _pypi(name: str, version: str) -> dict | None:
    body = fetch(f"https://pypi.org/pypi/{name}/{_base_version(version)}/json")
    if body is None:
        return None
    try:
        return json.loads(body)
    except json.JSONDecodeError as exc:
        print(f"  !! {name} {version}: {exc}")
        return None


def _from_artifact(release: dict) -> tuple[str, str, str] | None:
    """`(first line of the licence file, artifact filename!member, sha256)`.

    Read from the wheel the project actually publishes. The first non-empty
    line is recorded VERBATIM — "BSD 3-Clause License" is what the file says,
    and saying so is reporting, not a legal conclusion. Nothing is normalised
    to an SPDX identifier here, because that step would be an interpretation
    this script has no standing to make.
    """
    wheels = [u for u in release.get("urls", [])
              if u.get("packagetype") == "bdist_wheel"]
    if not wheels:
        return None
    wheel = min(wheels, key=lambda u: u.get("size", 1 << 40))
    blob = fetch(wheel["url"], timeout=180)
    if blob is None:
        return None

    digest = hashlib.sha256(blob).hexdigest()
    if digest != wheel["digests"]["sha256"]:
        print(f"  !! {wheel['filename']}: sha256 does not match what PyPI "
              f"published. Not reading a licence out of it.")
        return None

    try:
        archive = zipfile.ZipFile(io.BytesIO(blob))
    except zipfile.BadZipFile:
        return None
    members = [n for n in archive.namelist()
               if re.search(r"(LICEN[CS]E|COPYING)", n.upper())
               and not n.endswith("/")]
    for member in sorted(members):
        text = archive.read(member).decode("utf-8", "replace")
        for line in text.splitlines():
            if line.strip():
                return (line.strip(), f"{wheel['filename']}!{member}", digest)
    return None


def licence_of(name: str, version: str) -> tuple[str, bool, str, str | None]:
    """`(licence, resolved, source, artifact sha256)`.

    `resolved=False` means UNANSWERED — not unlicensed, and not permissive.
    The gate refuses to pass while any remain, rather than treating a failed
    fetch as an empty result.
    """
    release = _pypi(name, version)
    if release is None:
        return ("UNANSWERED", False, "pypi-json", None)
    info = release["info"]

    expression = (info.get("license_expression") or "").strip()
    if expression:
        return (expression, True, "pypi-json", None)
    legacy = (info.get("license") or "").strip()
    # Some projects dump their entire licence TEXT into this field. A 400-line
    # BSD notice is not a licence identifier and must not become one.
    if legacy and len(legacy) <= 120 and "\n" not in legacy:
        return (legacy, True, "pypi-json", None)
    classifiers = [c.split("::")[-1].strip()
                   for c in info.get("classifiers", [])
                   if c.startswith("License ::")]
    if classifiers:
        return (" AND ".join(sorted(set(classifiers))), True, "pypi-json", None)

    found = _from_artifact(release)
    if found is not None:
        line, where, digest = found
        return (line, True, f"artifact-licence-file: {where}", digest)
    if legacy:
        return ("UNDECLARED (licence text only, no identifier)", True,
                "pypi-json", None)
    return ("UNDECLARED", True, "pypi-json", None)


def main() -> int:
    packages = locked()
    print(f"resolving {len(packages)} packages across "
          f"{', '.join(lock.name for lock in LOCKS)}")

    inventory: dict[str, dict] = {}
    unresolved: list[str] = []
    for name, (version, lock_name) in sorted(packages.items()):
        licence, resolved, source, digest = licence_of(name, version)
        if not resolved:
            unresolved.append(name)
        entry = {
            "version": version,
            "licence": licence,
            "resolved": resolved,
            "source": source,
            "lock": lock_name,
        }
        if digest is not None:
            entry["artifact_sha256"] = digest
        if source.startswith("artifact-licence-file"):
            print(f"  {name} {version}: PyPI metadata declares nothing; the "
                  f"published wheel carries {licence!r}")
        inventory[name] = entry

    if unresolved:
        # Writing a partial inventory would hand the gate a file in which
        # "no licence answer" is indistinguishable from "not asked".
        print(f"::error::{len(unresolved)} package(s) could not be resolved: "
              f"{unresolved}. Nothing written — a partial inventory is worse "
              f"than a missing one, because it looks complete.")
        return 1

    INVENTORY.write_text(json.dumps({
        "generated_by": "scripts/build_licence_inventory.py",
        "source": "requirements.lock + requirements-torch.lock + PyPI JSON API",
        "package_count": len(inventory),
        "packages": inventory,
    }, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    # The SBOM is regenerated from the same measurement, so the two cannot
    # disagree about which tree they describe.
    existing = json.loads(SBOM.read_text(encoding="utf-8"))
    existing["components"] = [
        {"type": "library", "name": name, "version": meta["version"],
         "purl": f"pkg:pypi/{name}@{meta['version']}",
         "bom-ref": f"pkg:pypi/{name}@{meta['version']}"}
        for name, meta in sorted(inventory.items())]
    existing["dependencies"] = [{"ref": c["bom-ref"]}
                                for c in existing["components"]]
    existing["metadata"]["timestamp"] = datetime.now(timezone.utc).isoformat()
    existing["metadata"]["properties"] = [
        {"name": "ira:generated-by",
         "value": "scripts/build_licence_inventory.py"},
        {"name": "ira:source",
         "value": "requirements.lock + requirements-torch.lock"},
        {"name": "ira:licence-data",
         "value": "NOT IN THIS DOCUMENT — a requirements file carries no "
                  "licence metadata. See dependency-licences.json."},
    ]
    existing["version"] = int(existing.get("version", 1)) + 1
    SBOM.write_text(json.dumps(existing, indent=2, sort_keys=True) + "\n",
                    encoding="utf-8")

    print(f"  wrote {INVENTORY.name} and {SBOM.name}: {len(inventory)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
