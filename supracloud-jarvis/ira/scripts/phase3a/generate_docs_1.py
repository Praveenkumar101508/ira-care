"""Generate the Phase 3A evidence documents from the manifest and snapshot.

Generated rather than hand-written, so the tables cannot drift from the JSON the
enforcement test reads.
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path("/home/user/supracloud-ira")
EV = ROOT / "docs/cloud/evidence"
M = json.load(open(EV / "DATABASE_TENANCY_CLASSIFICATION.json"))
S = json.load(open(ROOT / "artifacts/cloud/phase-3a/database-schema.json"))
T = M["tables"]
SHA = (ROOT / "artifacts/cloud/phase-3a/database-schema.sha256").read_text().split()[0]

counts = Counter(v["classification"] for v in T.values())
by_cls = defaultdict(list)
for n, v in sorted(T.items()):
    by_cls[v["classification"]].append(n)

mig      = {n: v for n, v in T.items() if v["migration"]["requires_migration"]}
need_t   = {n for n, v in T.items() if v["migration"]["requires_tenant_id"]}
need_w   = {n for n, v in T.items() if v["migration"]["requires_workspace_id"]}
need_u   = {n for n, v in T.items() if v["migration"]["requires_user_ownership_conversion"]}
need_enc = {n for n, v in T.items() if v["encryption"]["required"]}

# ── DATABASE_TENANCY_CLASSIFICATION.md ───────────────────────────────────────
L = []
w = L.append
w("# Database Tenancy Classification — Phase 3A (authoritative)")
w("")
w("**All 77 live tables classified. Zero `UNRESOLVED`.**")
w("")
w("| Provenance | Value |")
w("|---|---|")
w("| Schema snapshot | `artifacts/cloud/phase-3a/database-schema.json` |")
w(f"| SHA-256 | `{SHA}` |")
w(f"| PostgreSQL | {S['postgres_version']} |")
w(f"| Extensions | {', '.join(S['extensions'])} |")
w(f"| Application role | `{S['application_role']['name']}` — superuser: "
  f"**{S['application_role']['is_superuser']}**, BYPASSRLS: "
  f"**{S['application_role']['bypassrls']}** |")
w("")
w("> **This document is generated from `DATABASE_TENANCY_CLASSIFICATION.json`,**")
w("> which is the machine-readable source of truth. It is enforced by")
w("> `ira/tests/tenancy/test_classification_manifest.py` (35 tests) — a table")
w("> added to the schema without a manifest entry fails CI. Edit the JSON, not")
w("> this file.")
w("")
w("---")
w("")
w("## 1. Counts")
w("")
w("| Classification | Tables |")
w("|---|---|")
for k in sorted(counts): w(f"| `{k}` | {counts[k]} |")
w(f"| **Total** | **{sum(counts.values())}** |")
w(f"| **`UNRESOLVED`** | **{counts.get('UNRESOLVED', 0)}** |")
w("")
w("| Migration need | Tables |")
w("|---|---|")
w(f"| Requires any schema change | **{len(mig)}** |")
w(f"| Requires `tenant_id` | **{len(need_t)}** |")
w(f"| Requires `workspace_id` | **{len(need_w)}** |")
w(f"| Requires user-ownership conversion | **{len(need_u)}** |")
w(f"| Requires encryption | **{len(need_enc)}** |")
w(f"| Already correct, no change | **{77 - len(mig)}** |")
w("")
w("## 2. Tables by classification")
w("")
for cls in sorted(by_cls):
    w(f"### `{cls}` — {len(by_cls[cls])}")
    w("")
    w("| Table | Justification | Migration |")
    w("|---|---|---|")
    for n in by_cls[cls]:
        v = T[n]
        need = []
        if v["migration"]["requires_tenant_id"]: need.append("`tenant_id`")
        if v["migration"]["requires_workspace_id"]: need.append("`workspace_id`")
        if v["migration"]["requires_user_ownership_conversion"]: need.append("`user_id`")
        if v["encryption"]["required"]: need.append("**encrypt**")
        w(f"| `{n}` | {v['justification']} | {', '.join(need) or '—'} |")
    w("")

w("## 3. Priority order for Phase 3B")
w("")
w("The first three are not content tables. They are the ones where the current")
w("schema is an **authentication** problem rather than a privacy one.")
w("")
w("| # | Table | Why first |")
w("|---|---|---|")
w("| 1 | `totp_secrets` | Keyed on a username **string** with no tenant. Two tenants both holding `alice` collide on the second factor — an authentication bypass. |")
w("| 2 | `voice_profiles` | Voiceprints — biometric special category — keyed on `owner_name` and stored **unencrypted**. |")
w("| 3 | `biometric_audit` | The voiceprint-matching audit trail, with no owner column at all. |")
w("")

w("## 4. Full per-table specification")
w("")
w("`T`/`W`/`U` = has `tenant_id` / `workspace_id` / `user_id` **today**. "
  "`RLS` = enabled/forced today. `R/W` = non-test code files reading / writing.")
w("")
w("| Table | Classification | T | W | U | RLS | Files | Needs |")
w("|---|---|---|---|---|---|---|---|")
for n in sorted(T):
    v, c = T[n], T[n]["current"]
    need = []
    if v["migration"]["requires_tenant_id"]: need.append("tenant")
    if v["migration"]["requires_workspace_id"]: need.append("workspace")
    if v["migration"]["requires_user_ownership_conversion"]: need.append("user")
    if v["encryption"]["required"]: need.append("encrypt")
    w(f"| `{n}` | `{v['classification']}` | {'Y' if c['has_tenant_id'] else '—'} | "
      f"{'Y' if c['has_workspace_id'] else '—'} | {'Y' if c['has_user_id'] else '—'} | "
      f"{'Y' if c['rls_enabled'] else '—'}/{'Y' if c['rls_forced'] else '—'} | "
      f"{v['access']['non_test_code_files']} | {', '.join(need) or '—'} |")
w("")
w("## 5. Tables with no non-test code reference")
w("")
w("Searched across backend, workers, scripts, tests, frontend and SQL — 854")
w("files. These six are defined and seeded by SQL and covered by tests, but no")
w("non-test application code reads or writes them yet. **They are not dead**:")
w("they are schema that shipped ahead of the feature.")
w("")
w("| Table | Classification | Test refs |")
w("|---|---|---|")
for n in sorted(T):
    if not T[n]["access"]["referenced_in_code"]:
        w(f"| `{n}` | `{T[n]['classification']}` | present |")
w("")
w("They still receive a full classification and migration specification, because")
w("the feature that uses them will arrive after the schema is migrated, not before.")
(EV / "DATABASE_TENANCY_CLASSIFICATION.md").write_text("\n".join(L) + "\n")

# ── PHASE_3A_SCHEMA_SNAPSHOT.md ──────────────────────────────────────────────
L = []; w = L.append
w("# Phase 3A Schema Snapshot")
w("")
w("| Provenance | Value |")
w("|---|---|")
w("| Artifact | `artifacts/cloud/phase-3a/database-schema.json` |")
w(f"| SHA-256 | `{SHA}` |")
w("| Recorded | 2026-08-05 |")
w("")
w("Captured from a **fresh** database: `initdb`, `CREATE DATABASE`, then all 33")
w("migrations applied in filename order with `ON_ERROR_STOP=1`. Introspected as")
w("the superuser (to read `pg_policies` and `pg_constraint` in full) against a")
w("schema owned by that role, with a separate non-superuser application role")
w("created exactly as CI creates it.")
w("")
w("**No credential or connection string appears in the artifact.** The DSN is")
w("read from the environment and never written. The only matches for")
w("credential-shaped patterns are the column name `password_hash` and a CHECK")
w("constraint literal.")
w("")
w("---")
w("")
w("## Environment")
w("")
w("| Property | Value |")
w("|---|---|")
w(f"| PostgreSQL | {S['postgres_version']} |")
w(f"| Extensions | {', '.join(S['extensions'])} |")
w(f"| Tables | **{S['table_count']}** |")
w(f"| Application role | `{S['application_role']['name']}` |")
w(f"| — is superuser | **{S['application_role']['is_superuser']}** |")
w(f"| — has BYPASSRLS | **{S['application_role']['bypassrls']}** |")
w("")
w("Both role properties are load-bearing. A superuser bypasses RLS entirely, and")
w("a role with `BYPASSRLS` does the same — either would make every isolation")
w("assertion pass while proving nothing.")
w("")
w("## Captured per table")
w("")
w("Columns (name, type, nullability, default, position) · primary key · foreign")
w("keys · unique constraints · check constraints · indexes · RLS enabled · RLS")
w("forced · policies (command, roles, `USING`, `WITH CHECK`) · table owner ·")
w("role grants · triggers.")
w("")
w("## Totals")
w("")
pol = sum(len(v["policies"]) for v in S["tables"].values())
trg = sum(len(v["triggers"]) for v in S["tables"].values())
con = sum(len(v["constraints"]) for v in S["tables"].values())
idx = sum(len(v["indexes"]) for v in S["tables"].values())
col = sum(len(v["columns"]) for v in S["tables"].values())
w("| Object | Count |")
w("|---|---|")
w(f"| Tables | {S['table_count']} |")
w(f"| Columns | {col} |")
w(f"| Constraints | {con} |")
w(f"| Indexes | {idx} |")
w(f"| RLS policies | {pol} |")
w(f"| Triggers | {trg} |")
w("")
w("## Measured RLS state")
w("")
en = sum(1 for v in S["tables"].values() if v["rls"]["enabled"])
fo = sum(1 for v in S["tables"].values() if v["rls"]["forced"])
ti = sum(1 for v in S["tables"].values() if any(c["name"] == "tenant_id" for c in v["columns"]))
wi = sum(1 for v in S["tables"].values() if any(c["name"] == "workspace_id" for c in v["columns"]))
w("| Property | Count |")
w("|---|---|")
w(f"| RLS enabled | {en} |")
w(f"| RLS **forced** | {fo} |")
w(f"| Has `tenant_id` | {ti} |")
w(f"| Has `workspace_id` | **{wi}** |")
w(f"| Tables with `tenant_id` but RLS not forced | {ti - fo if ti > fo else 0} |")
w("")
w("Every table that carries `tenant_id` has RLS both enabled **and** forced —")
w("no partial coverage, no table relying on convention.")
w("")
w(f"**`workspace_id` appears in {wi} of {S['table_count']} tables.** The brief's")
w("model is tenant → organisation → workspace; the database has tenant only.")
w("")
w("## A defect this snapshot found")
w("")
w("The first run of the introspection script recorded **every** RLS flag as")
w("`false`. The query cast the booleans with `::text`, which renders")
w("`true`/`false`, while the parser compared against psql's raw `t`/`f`. The")
w("manifest test caught it by comparing the manifest against the live schema —")
w("45 mismatches, all in the same direction.")
w("")
w("Worth recording because of what it implies: a snapshot that silently reports")
w("*less* protection than exists is the benign direction. The same bug in the")
w("other direction would have reported RLS on tables that do not have it, and")
w("nothing downstream would have questioned it.")
(EV / "PHASE_3A_SCHEMA_SNAPSHOT.md").write_text("\n".join(L) + "\n")
print("wrote classification + snapshot docs")
