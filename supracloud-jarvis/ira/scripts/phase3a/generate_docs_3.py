import json
from collections import defaultdict
from pathlib import Path

ROOT = Path("/home/user/supracloud-ira")
EV = ROOT / "docs/cloud/evidence"
M = json.load(open(EV / "DATABASE_TENANCY_CLASSIFICATION.json"))["tables"]

L=[]; w=L.append
w("# Phase 3A — Deletion and Retention Matrix")
w("")
w("What happens to every table under user deletion, membership removal,")
w("workspace deletion, tenant deletion, suspension, legal hold and backup")
w("expiry.")
w("")
w("Generated from `DATABASE_TENANCY_CLASSIFICATION.json`; enforced by")
w("`test_every_table_has_deletion_and_retention_behaviour` and")
w("`test_audit_evidence_is_not_cascade_deleted_with_the_tenant`.")
w("")
w("---")
w("")
w("## 1. The five distinct operations")
w("")
w("Collapsing these is how audit evidence gets destroyed by a routine cleanup.")
w("")
w("| Operation | Means | Reversible? |")
w("|---|---|---|")
w("| **Remove access** | membership revoked; rows untouched | yes — re-invite |")
w("| **Soft delete** | `deleted_at` set; excluded from retrieval | yes, within retention |")
w("| **Hard delete** | row removed | no |")
w("| **Cryptographic deletion** | the tenant DEK is shredded; ciphertext remains but is unreadable | no |")
w("| **Retained audit metadata** | shape kept, content redacted | content: no; shape: n/a |")
w("")
w("ADR-0004 and ADR-0008 already decided this split for the trust ledger and the")
w("last six tables. This matrix applies the same line to all 77.")
w("")
w("## 2. Rules by classification")
w("")
w("| Classification | User deletion | Tenant deletion | Workspace deletion | Membership removal |")
w("|---|---|---|---|---|")
seen=set()
for t in sorted(M):
    c = M[t]["classification"]
    if c in seen: continue
    seen.add(c)
    d = M[t]["deletion"]
    w(f"| `{c}` | {d['user_deletion']} | {d['tenant_deletion']} | {d['workspace_deletion']} | {d['membership_removal']} |")
w("")
w("## 3. The rules that are not obvious")
w("")
w("**Audit evidence survives tenant deletion.** Every `APPEND_ONLY_AUDIT` table")
w("is *redacted and retained*, never cascade-deleted. Deleting a tenant must not")
w("silently destroy the record of what that tenant did — that is the difference")
w("between erasure and evidence destruction, and it is why")
w("`test_audit_evidence_is_not_cascade_deleted_with_the_tenant` exists.")
w("")
w("**A user in two tenants survives one of them being deleted.** `users` is")
w("`IDENTITY_GLOBAL`; tenant deletion removes memberships and tenant-scoped rows,")
w("not the person. Getting this wrong deletes a paying customer's account because")
w("a trial tenant they once joined was closed.")
w("")
w("**Voiceprints are hard-deleted, never redacted.** A redacted biometric")
w("template is still a biometric template with fields blanked. `USER_PRIVATE`")
w("biometric data is removed and its key material shredded.")
w("")
w("**`tenant_data_keys` is shred-only and never exported.** It already carries a")
w("trigger enforcing that. Cryptographic deletion is the mechanism that makes")
w("tenant deletion meaningful for data already written to backups.")
w("")
w("## 4. Per-table matrix")
w("")
w("| Table | Class | User del | Tenant del | Workspace del | Legal hold | Retention |")
w("|---|---|---|---|---|---|---|")
for t in sorted(M):
    v = M[t]; d = v["deletion"]
    w(f"| `{t}` | `{v['classification']}` | {d['user_deletion']} | {d['tenant_deletion']} | "
      f"{d['workspace_deletion']} | {d['legal_hold']} | {v['retention']} |")
w("")
w("## 5. Backup and key expiry")
w("")
w("| Concern | Rule |")
w("|---|---|")
w("| Backup retention | independent of row deletion — a deleted row persists in backups until they expire |")
w("| Backup encryption | required; a backup is a full copy of every tenant's data |")
w("| Key destruction | shredding the tenant DEK renders that tenant's ciphertext unreadable **in backups too** — this is the only deletion that reaches a backup |")
w("| Restore | must not resurrect a deleted tenant. A restore replays the deletion log, or the DEK stays shredded |")
w("")
w("**The honest position:** hard-deleting a row does not remove it from a backup")
w("taken before the deletion. Cryptographic deletion is what makes the claim")
w("supportable, and it only works for data encrypted with a per-tenant key —")
w("which is why migration `030` matters beyond key rotation.")
w("")
w("## 6. Not yet specified")
w("")
w("| Item | Owner | Phase |")
w("|---|---|---|")
w("| Audit retention period (concrete duration) | **owner decision** | 4 |")
w("| Backup retention period | **owner decision** | 14 |")
w("| Legal-hold mechanism | design | 4 |")
w("| Suspension vs deletion semantics | design | 2 |")
w("")
w("No duration is invented here. A retention period asserted without a decision")
w("would be a compliance claim with nothing behind it.")
(EV / "PHASE_3A_DELETION_RETENTION_MATRIX.md").write_text("\n".join(L) + "\n")
