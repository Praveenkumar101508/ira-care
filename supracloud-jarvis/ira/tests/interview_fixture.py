"""A synthetic question bank, so the interview tests do not need the snapshot.

── Why the tests stopped using the real data ───────────────────────────────

`third_party/leetcode-companywise/NOTICE.md` has always said, in its own words:
the upstream repository **declares no licence**, the data underneath it was
scraped from LeetCode Premium against LeetCode's terms, and *"if IRA is ever
packaged for anyone but its owner, drop this file."*

IRA is now a hosted, multi-tenant, priced product. Committing
`data/interview/leetcode-companies.json` to this repository **is** the packaging
the notice warned about — 763 KB of unlicensed third-party data, redistributed
by the act of storing it here. P16-R3 removed it. That is a resolution rather
than a legal opinion: nothing here decides whether the data could be licensed,
only that this repository has no evidence it may redistribute it, and so does
not.

The feature is unchanged and still works. `interview/dataset.py` already treats
an absent snapshot as `DatasetUnavailable` naming the rebuild command, and the
API answers `503` — never empty results. An owner who wants the bank runs the
build command in `NOTICE.md` and gets it locally.

── What this fixture is ────────────────────────────────────────────────────

The same SHAPE, with fabricated contents: made-up problems with made-up
difficulties and made-up frequencies. Company slugs are real company names,
because a company name is not the asset — the question-to-company frequency
mapping is, and every number here is generated by the code below.

It is deterministic (a fixed seed) because several tests assert that a plan
built twice is identical, and it is generated rather than committed so that no
snapshot of anybody's data creeps back in through a fixture file.
"""
from __future__ import annotations

import json
import random
from pathlib import Path

WINDOWS = ("30d", "3m", "6m", "6m+", "all")
DIFFICULTIES = ("Easy", "Medium", "Hard")

#: Named explicitly because tests refer to them by name: prefix matching
#: ("goo" -> google), ambiguity ("a" -> refused, so several must start with
#: it), multi-word display names ("goldman-sachs" -> "Goldman Sachs"), the
#: acronym table ("ibm" -> "IBM"), and multi-company plans.
NAMED_COMPANIES = ("amazon", "google", "meta", "microsoft", "apple", "adobe",
                   "airbnb", "atlassian", "bloomberg", "uber", "goldman-sachs",
                   "ibm", "stripe")

#: Above the thresholds the tests assert on (>500 companies, >3000 questions),
#: which are there to catch a truncated or half-written dataset.
FILLER_COMPANIES = 650
QUESTIONS = 3400

#: A search term the tests use. Every third problem carries it in its title so
#: that ranking by company-count has something to rank.
SEARCH_TERM = "matrix"


def build(seed: int = 20260813) -> dict:
    """The whole bank, as `interview/dataset.py` expects to read it."""
    rng = random.Random(seed)

    questions = []
    for qid in range(1, QUESTIONS + 1):
        topic = SEARCH_TERM if qid % 3 == 0 else "graph" if qid % 3 == 1 else "queue"
        questions.append([
            qid,
            f"synthetic-{topic}-problem-{qid:04d}",
            f"Synthetic {topic.title()} Problem {qid}",
            DIFFICULTIES[qid % 3],
            round(30.0 + (qid % 500) / 10.0, 1),
        ])

    slugs = list(NAMED_COMPANIES) + [
        f"synthetic-company-{i:03d}" for i in range(FILLER_COMPANIES)]

    companies: dict[str, dict[str, list]] = {}
    for index, slug in enumerate(slugs):
        named = slug in NAMED_COMPANIES
        # The named companies are large, because the plan tests ask for 40-50
        # problems spread across three difficulties, and a plan that cannot be filled
        # is a different test. The filler set is deliberately uneven — some
        # have a handful of rows — because "a short bank says so" needs one.
        count = 400 + index * 7 if named else 4 + (index * 37) % 200
        picked = rng.sample(range(1, QUESTIONS + 1), count)
        rows = sorted(
            ([qid, round(rng.uniform(1.0, 100.0), 1)] for qid in picked),
            key=lambda row: (-row[1], row[0]))
        windows: dict[str, list] = {"all": rows}
        # Narrower windows are SUBSETS, as upstream's are — several tests
        # assert a narrower window never adds rows. Every fourth filler company
        # is missing its narrow windows entirely, because "a window a company
        # lacks is stated, not substituted" needs a company that lacks one.
        narrow = ("30d", "3m", "6m", "6m+")
        for position, window in enumerate(narrow, start=1):
            if not named and index % 4 == 3 and window in ("30d", "3m"):
                continue
            windows[window] = rows[: max(1, len(rows) // (5 - position + 1))]
        companies[slug] = {w: windows[w] for w in WINDOWS if w in windows}

    # Two universally-asked questions, so `asked_by` has a populated head to
    # assert on rather than whatever the sampler happened to favour. One of
    # each topic, because the tests reach them through a title search and a
    # search for one topic cannot surface a question titled with the other.
    for slug in companies:
        rows = companies[slug]["all"]
        for qid in (1, 3):
            if not any(row[0] == qid for row in rows):
                rows.insert(0, [qid, 100.0])
        rows.sort(key=lambda row: (-row[1], row[0]))

    return {
        "meta": {
            "source": "https://github.com/example/synthetic-interview-fixture",
            "upstream_commit": "0000000000000000000000000000000000000000",
            "snapshot": "2026-01-01",
            "companies": len(companies),
            "questions": len(questions),
            "windows": list(WINDOWS),
            "note": "SYNTHETIC FIXTURE — generated by tests/interview_fixture.py. "
                    "Every problem, difficulty and frequency here is fabricated. "
                    "It is not a snapshot of anything and must not be treated as "
                    "one.",
        },
        "questions": questions,
        "companies": companies,
    }


def write(directory: Path, seed: int = 20260813) -> Path:
    path = Path(directory) / "synthetic-companies.json"
    path.write_text(json.dumps(build(seed)), encoding="utf-8")
    return path
