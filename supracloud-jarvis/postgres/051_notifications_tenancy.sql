-- =============================================================================
-- 051_notifications_tenancy.sql — Phase 3C finding 3C-10
--
-- `notifications` gets a tenant, a workspace, and Row-Level Security.
--
-- ── What was wrong ─────────────────────────────────────────────────────────
--
-- 3C-03 found that every notification was published to one hardcoded Redis
-- channel and that `/ws/notifications` forwarded it to any client with a
-- decodable token. It fixed the channel.
--
-- The same payload — the same `title` and `body` — is ALSO persisted into this
-- table by `worker/notifier.py::_persist`, and read back by
-- `GET /api/v1/notifications`:
--
--     SELECT id, category, title, body, priority, channels_sent, read, created_at
--       FROM notifications
--      ORDER BY created_at DESC LIMIT $1
--
-- No tenant predicate. No tenant column to write one against. No RLS. The route
-- authorises with `require_auth` and opens a bare connection, so every
-- authenticated user in every tenant reads every notification in the
-- deployment. For a briefing that is the owner's own content; for the security
-- monitor it is their security events.
--
-- And it is not only a read:
--
--     UPDATE notifications SET read=TRUE WHERE id=$1     -- another tenant's row
--     DELETE FROM notifications WHERE read=TRUE          -- every tenant's rows
--
-- The DELETE has no predicate at all beyond `read`. One authenticated caller
-- clears the deployment.
--
-- ── Why 3C-03 did not catch it ─────────────────────────────────────────────
--
-- Because the fix was to the transport, and this is the store. The table has no
-- tenancy column, so it is invisible to every guard built in Batch 5C: the
-- workspace binding ratchet scans the seventeen workspace-scoped tables, the
-- RLS audits enumerate tables that HAVE policies, and a table with neither is
-- in none of those sets. **A table with no tenancy is not a table with weak
-- tenancy; it is a table nothing is looking at.**
--
-- ── Shape of the fix ───────────────────────────────────────────────────────
--
-- `tenant_id` NOT NULL, `workspace_id` NULLABLE.
--
-- The asymmetry is deliberate. A notification always belongs to a tenant: it is
-- generated by that tenant's briefing, monitor or reminder. It does not always
-- belong to a workspace — a billing warning or a security alert is a
-- tenant-level event, and forcing one to name a workspace would mean inventing
-- an answer. So the policy reads:
--
--     tenant_id = app.tenant_id
--     AND (workspace_id IS NULL OR workspace_id = app.workspace_id)
--
-- Tenant-wide notifications are visible from any of the tenant's workspaces;
-- workspace-scoped ones only from theirs. Note this is NOT the seventeen
-- tables' predicate, and the difference is intentional — copying that predicate
-- here would make every tenant-level notification permanently invisible,
-- because NULL never equals anything.
--
-- ── Backfill ───────────────────────────────────────────────────────────────
--
-- Existing rows are the private deployment's own. They are assigned
-- `PRIVATE_TENANT_ID` — the same deterministic constant `023` established — and
-- a NULL workspace, because there is no way to know which workspace an existing
-- notification belonged to and guessing would be worse than tenant scope.
--
-- Rollback: rollback/051_notifications_tenancy_down.sql
-- =============================================================================

BEGIN;

-- ─────────────────────────────────────────────────────────────────────────────
-- 0. Preflight
--
--    This migration is additive, but it asserts its starting state rather than
--    assuming it. A partially-applied earlier attempt would otherwise produce a
--    confusing failure three statements later.
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
BEGIN
    IF to_regclass('public.notifications') IS NULL THEN
        RAISE EXCEPTION
            '051 REFUSING: table notifications does not exist. Run the earlier '
            'migrations first.';
    END IF;

    IF EXISTS (
        SELECT 1 FROM pg_policy WHERE polrelid = 'public.notifications'::regclass
    ) THEN
        RAISE EXCEPTION
            '051 REFUSING: notifications already carries % policy(ies). This '
            'migration creates them and will not silently replace a policy set '
            'it did not write.',
            (SELECT count(*) FROM pg_policy
              WHERE polrelid = 'public.notifications'::regclass);
    END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Columns
--
--    `workspace_id` has NO default reading `app.workspace_id`. The seventeen
--    content tables do, because content always belongs to a workspace. A
--    notification does not, and a default would silently attach every
--    tenant-level alert to whichever workspace happened to be bound when it was
--    written — making it invisible from the tenant's other workspaces.
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE notifications
    ADD COLUMN IF NOT EXISTS tenant_id uuid,
    ADD COLUMN IF NOT EXISTS workspace_id uuid;

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Backfill
--
--    No RLS window is needed: RLS is enabled in step 4, below. This is the
--    ordering `045` got wrong in the other direction — it opened a window over
--    the tables it wrote and not over the table it READ, and backfilled
--    nothing while reporting success. Here nothing is read and nothing is yet
--    enforcing, so the UPDATE reaches every row. Step 3 asserts that it did.
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE notifications
   SET tenant_id = 'e91aceeb-89fb-5ad2-b43c-4eee2bad079c'::uuid
 WHERE tenant_id IS NULL;

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Assert the backfill actually happened before constraining on it
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE
    remaining bigint;
BEGIN
    SELECT count(*) INTO remaining FROM notifications WHERE tenant_id IS NULL;
    IF remaining > 0 THEN
        RAISE EXCEPTION
            '051 REFUSING: % notification row(s) still have a NULL tenant_id '
            'after the backfill. SET NOT NULL would fail next; refusing here '
            'names the count instead.', remaining;
    END IF;
END $$;

ALTER TABLE notifications
    ALTER COLUMN tenant_id SET NOT NULL;

ALTER TABLE notifications
    ADD CONSTRAINT notifications_tenant_id_fkey
    FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE;

ALTER TABLE notifications
    ADD CONSTRAINT notifications_workspace_id_fkey
    FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE RESTRICT;

-- A workspace-scoped notification must name a workspace belonging to its own
-- tenant. The FK above only proves the workspace exists; this proves it is the
-- right tenant's, which a single-column FK cannot express.
ALTER TABLE notifications
    ADD CONSTRAINT notifications_workspace_in_tenant_fkey
    FOREIGN KEY (tenant_id, workspace_id) REFERENCES workspaces (tenant_id, id)
    ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS idx_notifications_tenant
    ON notifications (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_tenant_unread
    ON notifications (tenant_id, created_at DESC) WHERE read = false;

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. Row-Level Security
--
--    FORCE, so the schema owner is bound too. Without FORCE the owner reads
--    everything and the "unbound connection sees nothing" test would pass only
--    because the test connects as `ira_app`.
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications FORCE ROW LEVEL SECURITY;

-- Per-command rather than FOR ALL, because the four differ: a caller may read
-- and update a tenant-level notification it can see, but may only INSERT one
-- into a workspace it is bound to.
CREATE POLICY tenant_scoped_select ON notifications FOR SELECT
    USING (
        tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid
        AND (workspace_id IS NULL
             OR workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::uuid)
    );

CREATE POLICY tenant_scoped_insert ON notifications FOR INSERT
    WITH CHECK (
        tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid
        AND (workspace_id IS NULL
             OR workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::uuid)
    );

CREATE POLICY tenant_scoped_update ON notifications FOR UPDATE
    USING (
        tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid
        AND (workspace_id IS NULL
             OR workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::uuid)
    )
    WITH CHECK (
        tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid
        AND (workspace_id IS NULL
             OR workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::uuid)
    );

CREATE POLICY tenant_scoped_delete ON notifications FOR DELETE
    USING (
        tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid
        AND (workspace_id IS NULL
             OR workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::uuid)
    );

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. Assert the end state
--
--    Written out rather than trusted, for the reason 3C-06 established: a
--    policy that exists is not a policy that denies, and the only thing a
--    migration can check cheaply is that it wrote what it meant to. The
--    adversarial proof is `tests/tenancy/test_3c10_unscoped_tables.py`.
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE
    n_policies int;
    forced boolean;
BEGIN
    SELECT count(*) INTO n_policies
      FROM pg_policy WHERE polrelid = 'public.notifications'::regclass;
    IF n_policies <> 4 THEN
        RAISE EXCEPTION
            '051 FAILED: notifications has % policies, expected 4 '
            '(select/insert/update/delete).', n_policies;
    END IF;

    SELECT relforcerowsecurity INTO forced
      FROM pg_class WHERE oid = 'public.notifications'::regclass;
    IF NOT forced THEN
        RAISE EXCEPTION
            '051 FAILED: notifications does not have FORCE ROW LEVEL SECURITY, '
            'so the schema owner still reads every tenant.';
    END IF;

    IF EXISTS (
        SELECT 1 FROM pg_policy
         WHERE polrelid = 'public.notifications'::regclass
           AND coalesce(pg_get_expr(polqual, polrelid), '')
               || coalesce(pg_get_expr(polwithcheck, polrelid), '')
               NOT LIKE '%app.tenant_id%'
    ) THEN
        RAISE EXCEPTION
            '051 FAILED: a notifications policy does not read app.tenant_id.';
    END IF;
END $$;

COMMIT;
